# Smooth natural land boundaries with quadratic corner arcs. Road/water data above
# is authored independently; no automated smoothing can turn lettering into roads.
import re
import math
raw = json.loads((ROOT/'src/data/campus-layout.json').read_text(encoding='utf8'))


def road_label(name, target, tier=1):
    """Place text exactly on its road centerline, tangent to that road.

    The nearest sampled parameter is evaluated on the actual quadratic, rather
    than snapping to a linear approximation. Road labels must never be displaced.
    """
    path=next(p for n,w,p in roads if n == name)
    samples=[]
    for command, coordinates in re.findall(r'([MLQ])([^MLQ]+)',path):
        v=list(map(float,re.findall(r'-?\d+(?:\.\d+)?',coordinates)))
        if command=='M': current=v; continue
        start=current
        current=v[-2:]
        for i in range(101):
            t=i/100
            if command=='L':
                x,y=[a+(b-a)*t for a,b in zip(start,current)]
                dx,dy=[b-a for a,b in zip(start,current)]
            else:
                x,y=[(1-t)**2*a+2*(1-t)*t*b+t*t*c for a,b,c in zip(start,v[:2],current)]
                dx,dy=[2*((1-t)*(b-a)+t*(c-b)) for a,b,c in zip(start,v[:2],current)]
            samples.append(((x-target[0])**2+(y-target[1])**2,x,y,math.degrees(math.atan2(dy,dx))))
    _,x,y,angle=min(samples)
    if angle>90: angle-=180
    if angle<-90: angle+=180
    return {'name':name,'x':x,'y':y,'rotation':angle,'tier':tier,'kind':'road'}


