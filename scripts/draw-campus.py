def smooth(path):
    result=[]
    for ring in path.split('Z'):
        pts=[tuple(map(float,p)) for p in re.findall(r'(-?[\d.]+),(-?[\d.]+)',ring)]
        if len(pts)<3: continue
        mids=[((p[0]+pts[(i+1)%len(pts)][0])/2,(p[1]+pts[(i+1)%len(pts)][1])/2) for i,p in enumerate(pts)]
        result.append(f'M{mids[-1][0]:g},{mids[-1][1]:g}'+''.join(f'Q{p[0]:g},{p[1]:g} {m[0]:g},{m[1]:g}' for p,m in zip(pts,mids))+'Z')
    return ' '.join(result)


